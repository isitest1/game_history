def child_weight(x):
    """子ども（1〜14歳）の死亡の上乗せの年齢の形。天然痘（牛痘種痘の前）や麻疹などで
    幼児の死亡が多かったとみて、1〜4歳を1、5〜9歳を0.6、10〜14歳を0.3 とした（仮定）。"""
    if 1 <= x <= 4:
        return 1.0
    if 5 <= x <= 9:
        return 0.6
    if 10 <= x <= 14:
        return 0.3
    return 0.0


