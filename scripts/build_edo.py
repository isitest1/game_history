def a0(q0, sex):
    """0歳の平均生存年数（Coale-Demeny）。"""
    if sex == "male":
        return 0.045 + 2.684 * q0 if q0 < 0.107 else 0.330
    return 0.053 + 2.800 * q0 if q0 < 0.107 else 0.350


def life_table(q, sex):
    q = [min(max(v, 1e-7), 1.0) for v in q]
    q[-1] = 1.0
    l = [1.0] * 106
    for x in range(1, 106):
        l[x] = l[x - 1] * (1 - q[x - 1])
    d = [l[x] * q[x] for x in range(106)]
    L = [l[x] - 0.5 * d[x] for x in range(106)]
    L[0] = l[0] - d[0] + a0(q[0], sex) * d[0]
    mu = -math.log(max(1 - q[104], 1e-6)) * 1.05
    L[105] = l[105] / max(mu, 0.3)
    T = [0.0] * 106
    acc = 0.0
    for x in range(105, -1, -1):
        acc += L[x]
        T[x] = acc
    e = [T[x] / max(l[x], 1e-300) for x in range(106)]
    return l, L, e


def e0(q, sex):
    return life_table(q, sex)[2][0]


def logit(v):
    v = min(max(v, 1e-7), 1 - 1e-7)
    return math.log(v / (1 - v))


def expit(z):
    return 1 / (1 + math.exp(-z))


def make_table(base, sex, q0, adult, maternal, child):
    """1890年の表 base の logit(qx) をずらして過去の表を作る。
    0歳は q0 そのもの。1歳以上は adult（一様）＋ child×child_weight(x)＋（女の18〜44歳）maternal。"""
    q = [0.0] * 106
    q[0] = q0
    for x in range(1, 105):
        z = logit(base[x]) + adult + child * child_weight(x)
        if sex == "female" and 18 <= x <= 44:
            z += maternal
        q[x] = expit(z)
    q[105] = 1.0
    return q


def solve_child(base, sex, q0, adult, maternal, target):
    """平均寿命が target になる子どもの上乗せ child を二分法で求める。"""
    lo, hi = -1.0, 4.0
    for _ in range(80):
        mid = (lo + hi) / 2
        if e0(make_table(base, sex, q0, adult, maternal, mid), sex) > target:
            lo = mid
        else:
            hi = mid
    return (lo + hi) / 2


def stable_cbr(tables, r):
    """安定人口の出生率（男女計）。人口増加率 r、出生性比 SRB。"""
    share = {"male": SRB / (1 + SRB), "female": 1 / (1 + SRB)}
    s = 0.0
    for sex in SEXES:
        _, L, _ = life_table(tables[sex], sex)
        s += share[sex] * sum(L[x] * math.exp(-r * (x + 0.5)) for x in range(106))
    return 1 / s


def stable_tfr(tables, r):
    """安定人口から合計出生率の目安を出す。NRR = exp(r×T)（T=平均世代間隔29年）、
    TFR = NRR ×(1+SRB) ÷ l_f(29)。"""
    T = 29.0
    l, _, _ = life_table(tables["female"], "female")
    nrr = math.exp(r * T)
    return nrr * (1 + SRB) / l[29]


def interp_points(points, years):
    """{年: 値} を直線補間（両端の外は端の値）。"""
    ks = sorted(points)
    out = {}
    for y in years:
        if y <= ks[0]:
            out[y] = points[ks[0]]
            continue
        if y >= ks[-1]:
            out[y] = points[ks[-1]]
            continue
        for a, b in zip(ks, ks[1:]):
            if a <= y <= b:
                t = (y - a) / (b - a)
                out[y] = points[a] + t * (points[b] - points[a])
                break
    return out


def r4(v):
    return float(f"{v:.4g}")


