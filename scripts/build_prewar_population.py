def a0(q0, sex):
    """0歳の平均生存年数（Coale-Demeny）。"""
    if sex == "male":
        return 0.045 + 2.684 * q0 if q0 < 0.107 else 0.330
    return 0.053 + 2.800 * q0 if q0 < 0.107 else 0.350


def life_table(q, sex):
    q = np.clip(np.asarray(q, float), 1e-7, 1.0)
    q[-1] = 1.0
    l = np.ones(106)
    for x in range(1, 106):
        l[x] = l[x - 1] * (1 - q[x - 1])
    d = l * q
    L = l - d + 0.5 * d
    L[0] = l[0] - d[0] + a0(q[0], sex) * d[0]
    mu = -math.log(max(1 - q[104], 1e-6)) * 1.05
    L[105] = l[105] / max(mu, 0.3)
    T = np.cumsum(L[::-1])[::-1]
    return l, L, T / np.maximum(l, 1e-300)


def e0(q, sex):
    return float(life_table(q, sex)[2][0])


def logit(q):
    q = np.clip(q, 1e-7, 1 - 1e-7)
    return np.log(q / (1 - q))


def expit(z):
    return 1 / (1 + np.exp(-z))


def table_q(k, sex):
    """生命表 k 回の qx を 0..105 の配列にする。105歳まで載っていない年齢は、
    最後の15歳分の logit(qx) を一次式で延ばす。q105=1。"""
    vals = [float(v) for v in QX[(k, sex)].split()]
    while vals and vals[-1] >= 0.9999:   # 最後の q=1（開放区間）は使わない
        vals.pop()
    q = np.full(106, np.nan)
    n = min(len(vals), 105)
    q[:n] = vals[:n]
    if n < 105:
        xs = np.arange(n - 15, n)
        b, c = np.polyfit(xs, logit(q[xs]), 1)
        for a in range(n, 105):
            q[a] = expit(b * a + c)
    q[105] = 1.0
    return q


def parse_vital():
    v = {}
    for line in VITAL.strip().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        p = line.split()
        y = int(p[0])
        b, bm, bf, d = (int(x) for x in p[1:5])
        assert 0 <= b - (bm + bf) <= 1, y   # 1926年は男女不詳1を含む（第4.1表の注）
        v[y] = {"births": b, "bm": bm, "bf": bf, "deaths": d, "cdr": float(p[5]),
                "infdeaths": int(p[6]), "imr": float(p[7])}
    assert sorted(v) == list(range(1899, 1930))
    return v


