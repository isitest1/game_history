    def interp(y, s, anchor):
        ks = sorted(TABLES)
        if y <= mid[ks[0]]:
            return anchor[ks[0]][s].copy()
        if y >= mid[ks[-1]]:
            return anchor[ks[-1]][s].copy()
        for a, b in zip(ks, ks[1:]):
            if mid[a] <= y <= mid[b]:
                w = (y - mid[a]) / (mid[b] - mid[a])
                z = (1 - w) * logit(anchor[a][s][:105]) + w * logit(anchor[b][s][:105])
                return np.append(expit(z), 1.0)

