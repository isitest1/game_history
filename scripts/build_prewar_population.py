    # --- 0歳: 乳児死亡率 → q0 の換算比（生命表の q0 ÷ 期間の乳児死亡率）
    def imr_avg(y0, y1):
        ys = [y for y in range(y0, y1 + 1) if y in vital]
        return sum(vital[y]["infdeaths"] for y in ys) / sum(vital[y]["births"] for y in ys)

    ratio = {}
    for k in (2, 3, 4, 5):
        r = imr_avg(TABLES[k][1], min(TABLES[k][2], 1929) if k != 5 else 1929)
        ratio[k] = {s: base[k][s][0] / r for s in SEXES}

    def q0_ratio(y, s):
        ks = sorted(ratio)
        if y <= mid[ks[0]]:
            return ratio[ks[0]][s]
        if y >= mid[ks[-1]]:
            return ratio[ks[-1]][s]
        for a, b in zip(ks, ks[1:]):
            if mid[a] <= y <= mid[b]:
                w = (y - mid[a]) / (mid[b] - mid[a])
                return (1 - w) * ratio[a][s] + w * ratio[b][s]

