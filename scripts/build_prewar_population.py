    for y in FLU_YEARS:
        basev = b0 + (b1 - b0) * (y - 1916.5) / 5.0
        flu[y] = {"observed": round(noninf_rate(y), 2), "baseline": round(basev, 2),
                  "ratio": round(noninf_rate(y) / basev, 4)}

